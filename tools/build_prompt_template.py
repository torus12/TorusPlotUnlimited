#!/usr/bin/env python
"""Write docs/PROMPT_TEMPLATE_FOR_OUTSIDE_AI.md from the FigureSpec schema.

    python tools/build_prompt_template.py           # (re)write the document
    python tools/build_prompt_template.py --check   # exit 1 if the document is out of date

The document is generated by ``torusplot.ai.outside.outside_prompt_template()`` so that it
can never drift from the schema; ``tests/ai/test_outside.py`` checks the committed file.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DOC = ROOT / "docs" / "PROMPT_TEMPLATE_FOR_OUTSIDE_AI.md"


def build() -> str:
    if str(ROOT) not in sys.path:
        sys.path.insert(0, str(ROOT))
    from torusplot.ai.outside import outside_prompt_template

    return outside_prompt_template()


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=(__doc__ or "").split("\n")[0])
    parser.add_argument("--check", action="store_true", help="Only check that the document is up to date")
    parser.add_argument("--output", type=Path, default=DOC, help="Where to write the document")
    args = parser.parse_args(argv)

    text = build()
    current = args.output.read_text(encoding="utf-8") if args.output.is_file() else None
    if args.check:
        if current != text:
            print(f"{args.output} is out of date. Run: python tools/build_prompt_template.py")
            return 1
        print(f"{args.output} is up to date.")
        return 0
    args.output.parent.mkdir(parents=True, exist_ok=True)
    with args.output.open("w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)
    print(f"Wrote {args.output} ({len(text)} characters).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
